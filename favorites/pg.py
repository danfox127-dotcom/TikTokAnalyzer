"""The library in Postgres -- Supabase, so the museum can live in the cloud.

The museum was written for SQLite, and on a Mac it still runs on SQLite. With
``DATABASE_URL`` set it keeps the library in Postgres instead, through the
small adapter here: a connection that answers the way a ``sqlite3`` one does
-- ``conn.execute(sql, params).fetchone()["n"]`` and all -- so the rest of the
code, some 140 queries, is the same either way.

The queries are written in what the two databases share. Where SQLite has a
function Postgres lacks -- ``json_each`` and ``json_array_length`` over a JSON
list kept as text, ``julianday`` -- the schema below defines one with the same
name and meaning, so a query never needs a second version. SQLite's
case-blind ``COLLATE NOCASE`` is a collation of the same name. Full-text
search is the one real difference (FTS5 against ``tsvector``); ``db.py`` keeps
both forms of it side by side.

Each library is a schema of its own (``faves`` unless ``FAVORITES_PG_SCHEMA``
says otherwise), which keeps it clear of anything else in the database and
out of reach of Supabase's public data API.
"""

from __future__ import annotations

import os
import re
import sqlite3
import threading
from functools import lru_cache

import psycopg
from psycopg.adapt import Dumper

DEFAULT_SCHEMA = "faves"

SCHEMA = """
CREATE SCHEMA IF NOT EXISTS {schema};
SET search_path TO {schema}, public, extensions;

-- SQLite's COLLATE NOCASE: equal whatever the capitals.
DO $$ BEGIN
  CREATE COLLATION nocase (provider = icu, locale = 'und-u-ks-level2', deterministic = false);
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

CREATE TABLE IF NOT EXISTS items (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    canonical_url  TEXT NOT NULL UNIQUE,
    shared_url     TEXT NOT NULL,
    platform       TEXT NOT NULL,
    external_id    TEXT,
    title          TEXT,
    creator_name   TEXT,
    creator_handle TEXT,
    creator_url    TEXT,
    thumbnail_url  TEXT,
    description    TEXT,
    transcript     TEXT,
    note           TEXT,
    tags           TEXT NOT NULL DEFAULT '[]',
    terms          TEXT NOT NULL DEFAULT '[]',
    saved_at       TEXT NOT NULL,
    resolved_at    TEXT,
    resolve_status TEXT NOT NULL DEFAULT 'pending',
    resolve_error  TEXT,
    resolve_attempts INTEGER NOT NULL DEFAULT 0,
    source         TEXT NOT NULL DEFAULT 'share',
    imported_at    TEXT,
    format         TEXT,
    themes         TEXT NOT NULL DEFAULT '[]',
    duration       INTEGER,
    raw            TEXT
);
CREATE INDEX IF NOT EXISTS idx_items_saved_at ON items(saved_at DESC);
CREATE INDEX IF NOT EXISTS idx_items_platform ON items(platform);
CREATE INDEX IF NOT EXISTS idx_items_creator  ON items(creator_handle);
CREATE INDEX IF NOT EXISTS idx_items_status   ON items(resolve_status);

CREATE TABLE IF NOT EXISTS collections (
    item_id  INTEGER NOT NULL REFERENCES items(id) ON DELETE CASCADE,
    name     TEXT NOT NULL,
    added_at TEXT,
    PRIMARY KEY (item_id, name)
);
CREATE INDEX IF NOT EXISTS idx_collections_name ON collections(name);

CREATE TABLE IF NOT EXISTS thumbnails (
    item_id      INTEGER PRIMARY KEY REFERENCES items(id) ON DELETE CASCADE,
    content_type TEXT NOT NULL,
    data         BYTEA NOT NULL,
    source_url   TEXT,
    fetched_at   TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS theme_rules (
    kind       TEXT NOT NULL,
    key        TEXT NOT NULL,
    theme      TEXT NOT NULL,
    action     TEXT NOT NULL,
    created_at TEXT,
    PRIMARY KEY (kind, key, theme)
);

CREATE TABLE IF NOT EXISTS imports (
    key         TEXT PRIMARY KEY,
    filename    TEXT NOT NULL,
    platform    TEXT NOT NULL,
    imported_at TEXT NOT NULL,
    added       INTEGER NOT NULL DEFAULT 0,
    detail      TEXT
);

CREATE TABLE IF NOT EXISTS inbox_seen (
    line_hash TEXT PRIMARY KEY,
    seen_at   TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS meta (
    key   TEXT PRIMARY KEY,
    value TEXT
);

-- SQLite's json_each over a JSON list kept as text, and its length.
CREATE OR REPLACE FUNCTION json_each(text) RETURNS TABLE (key integer, value text)
LANGUAGE sql IMMUTABLE AS $$
  SELECT (o - 1)::integer, v
  FROM jsonb_array_elements_text(coalesce(nullif($1, ''), '[]')::jsonb) WITH ORDINALITY AS t(v, o)
$$;
CREATE OR REPLACE FUNCTION json_array_length(text) RETURNS integer
LANGUAGE sql IMMUTABLE AS $$
  SELECT jsonb_array_length(coalesce(nullif($1, ''), '[]')::jsonb)
$$;
-- SQLite's julianday: days since noon, 24 November 4714 BC. Only ever
-- subtracted from another, so only the difference has to agree.
CREATE OR REPLACE FUNCTION julianday(text) RETURNS double precision
LANGUAGE sql IMMUTABLE AS $$
  SELECT extract(epoch FROM $1::timestamp) / 86400.0 + 2440587.5
$$;

-- Accents fold away for search, as SQLite's remove_diacritics does: "cafe"
-- finds "café". unaccent where the database has it (Supabase keeps extensions
-- in a schema of their own), else words as they are.
DO $$ BEGIN
  CREATE SCHEMA IF NOT EXISTS extensions;
  CREATE EXTENSION IF NOT EXISTS unaccent SCHEMA extensions;
EXCEPTION WHEN OTHERS THEN NULL; END $$;
DO $$ BEGIN
  IF to_regprocedure('extensions.unaccent(regdictionary,text)') IS NOT NULL THEN
    EXECUTE 'CREATE OR REPLACE FUNCTION fold(text) RETURNS text LANGUAGE sql IMMUTABLE AS '
            '$f$ SELECT lower(extensions.unaccent(''extensions.unaccent''::regdictionary, coalesce($1, ''''))) $f$';
  ELSE
    EXECUTE 'CREATE OR REPLACE FUNCTION fold(text) RETURNS text LANGUAGE sql IMMUTABLE AS '
            '$f$ SELECT lower(coalesce($1, '''')) $f$';
  END IF;
END $$;

-- Search: the same columns as SQLite's items_fts, with the words indexed.
CREATE TABLE IF NOT EXISTS items_fts (
    item_id     INTEGER NOT NULL,
    title       TEXT,
    creator     TEXT,
    description TEXT,
    note        TEXT,
    transcript  TEXT,
    tags        TEXT,
    doc tsvector GENERATED ALWAYS AS (to_tsvector('simple', fold(
        coalesce(title, '') || ' ' || coalesce(creator, '') || ' ' || coalesce(description, '')
        || ' ' || coalesce(note, '') || ' ' || coalesce(transcript, '') || ' ' || coalesce(tags, '')))) STORED
);
CREATE INDEX IF NOT EXISTS idx_items_fts_item ON items_fts(item_id);
CREATE INDEX IF NOT EXISTS idx_items_fts_doc ON items_fts USING gin (doc);
"""

#: Schemas this process has already set up, so a request doesn't redo it.
_READY: set[tuple[str, str]] = set()
_SETTING_UP = threading.Lock()

#: Setting up a schema takes this advisory lock first, so two servers starting
#: at once take turns: run side by side, Postgres rejects the second one's
#: CREATE OR REPLACE ("tuple concurrently updated").
_SETUP_LOCK = 0x46617665  # "Fave"


def url() -> str:
    return os.environ.get("DATABASE_URL", "")


def schema() -> str:
    name = os.environ.get("FAVORITES_PG_SCHEMA") or DEFAULT_SCHEMA
    if not re.fullmatch(r"[a-z_][a-z0-9_]{0,62}", name):
        raise ValueError(f"not a usable schema name: {name!r}")
    return name


class Row:
    """A result row that reads like ``sqlite3.Row``: by name, by position, as a dict."""

    __slots__ = ("_names", "_values")

    def __init__(self, names: tuple[str, ...], values: tuple):
        self._names, self._values = names, values

    def __getitem__(self, key):
        if isinstance(key, (int, slice)):
            return self._values[key]
        return self._values[self._names.index(key)]

    def keys(self) -> list[str]:
        return list(self._names)

    def __iter__(self):
        return iter(self._values)

    def __len__(self) -> int:
        return len(self._values)

    def __repr__(self) -> str:
        return f"Row({dict(zip(self._names, self._values))!r})"


def _rows(cursor):
    names = tuple(d.name for d in cursor.description or ())
    return lambda values: Row(names, values)


class _Loose(Dumper):
    """Send numbers untyped and let Postgres infer, the way SQLite compares
    them -- so ``key = ?`` works whether the key column is text or a number."""

    oid = 0

    def dump(self, obj):
        return str(int(obj)).encode()


class Cursor:
    def __init__(self, cur, lastrowid=None):
        self._cur, self.lastrowid = cur, lastrowid

    @property
    def rowcount(self) -> int:
        return self._cur.rowcount

    def fetchone(self):
        return self._cur.fetchone() if self._cur.description else None

    def fetchall(self) -> list:
        return self._cur.fetchall() if self._cur.description else []

    def __iter__(self):
        return iter(self.fetchall())


_QMARK = re.compile(r"\?")


@lru_cache(maxsize=1024)
def translate(sql: str) -> str:
    """SQLite's ``?`` placeholders as psycopg's ``%s``; a literal ``%`` doubled."""
    return _QMARK.sub("%s", sql.replace("%", "%%"))


class Connection:
    """A Postgres connection that answers like a ``sqlite3`` one.

    Errors come back as ``sqlite3`` errors too -- after rolling back, as
    Postgres needs -- so code that falls back when a search can't be run
    works unchanged.
    """

    row_factory = None

    def __init__(self, raw: psycopg.Connection):
        self._raw = raw

    def _run(self, fn):
        try:
            return fn()
        except psycopg.errors.IntegrityError as exc:
            self._raw.rollback()
            raise sqlite3.IntegrityError(str(exc)) from exc
        except psycopg.Error as exc:
            self._raw.rollback()
            raise sqlite3.OperationalError(str(exc)) from exc

    def execute(self, sql: str, params=()) -> Cursor:
        cur = self._raw.cursor(row_factory=_rows)
        # Always a tuple, even an empty one, so a doubled "%" reads as one.
        self._run(lambda: cur.execute(translate(sql), tuple(params)))
        return Cursor(cur)

    def executemany(self, sql: str, seq) -> Cursor:
        cur = self._raw.cursor(row_factory=_rows)
        rows = [tuple(p) for p in seq]
        if rows:
            self._run(lambda: cur.executemany(translate(sql), rows))
        return Cursor(cur)

    def commit(self) -> None:
        self._raw.commit()

    def rollback(self) -> None:
        self._raw.rollback()

    def close(self) -> None:
        self._raw.close()

    @property
    def closed(self) -> bool:
        return self._raw.closed


def connect() -> Connection:
    """Open the library in Postgres, setting up its schema the first time."""
    name = schema()
    raw = psycopg.connect(url(), prepare_threshold=None, autocommit=True)
    # Said as a statement rather than a connection option: Supabase's pooler
    # passes statements through but can drop options. Outside a transaction,
    # so a later rollback can't undo it.
    raw.execute(f"SET search_path TO {name}, public, extensions")
    raw.autocommit = False
    for kind in (int, bool):
        raw.adapters.register_dumper(kind, _Loose)
    if (url(), name) not in _READY:
        # A page's pictures arrive together: one request sets the schema up,
        # the rest wait for it rather than all trying at once.
        with _SETTING_UP:
            if (url(), name) not in _READY:
                with raw.cursor() as cur:
                    cur.execute(f"SELECT pg_advisory_xact_lock({_SETUP_LOCK})")
                    cur.execute(SCHEMA.replace("{schema}", name))
                raw.commit()
                _READY.add((url(), name))
    return Connection(raw)


def drop(name: str, where: str = "") -> None:
    """Remove a library's schema and everything in it (the tests' clean-up)."""
    with psycopg.connect(where or url(), autocommit=True) as raw:
        raw.execute(f"DROP SCHEMA IF EXISTS {name} CASCADE")
    _READY.difference_update({k for k in _READY if k[1] == name})
